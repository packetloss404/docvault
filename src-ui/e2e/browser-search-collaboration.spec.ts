import { test, expect } from '@playwright/test';
import { readFile } from 'node:fs/promises';
import { authHeaders, baseURL, login, uniqueName } from './support/api';
import { authenticatePage, sha256, uploadPdf } from './support/documents';

test('full-text search, rich filters, global palette and a pinned saved view return the ingested document', async ({ page, request }) => {
  test.setTimeout(240_000);
  const token = await login(request);
  const title = uniqueName('Searchable browser invoice');
  const { doc } = await uploadPdf(request, token, title);
  await expect.poll(async () => {
    const response = await request.get(`${baseURL}/api/v1/search/`, { headers: authHeaders(token), params: { query: title } });
    expect(response.ok()).toBeTruthy();
    return (await response.json()).results.some((item: { id: number }) => item.id === doc.id);
  }, { timeout: 60_000 }).toBe(true);
  await authenticatePage(page, token);
  await page.goto('/search');
  await page.getByRole('textbox', { name: 'Search documents', exact: true }).fill(title);
  await page.getByRole('button', { name: 'Search', exact: true }).click();
  await expect(page.locator('.sr-result').filter({ hasText: title })).toBeVisible();
  await page.getByRole('button', { name: '+ where', exact: true }).click();
  await page.getByLabel('Filter 1 field').selectOption('title');
  await page.getByLabel('Filter 1 operator').selectOption('equals');
  await page.getByLabel('Filter 1 value').fill('a title that does not exist');
  await page.getByRole('button', { name: 'apply ↵', exact: true }).click();
  await expect(page.locator('.sr-result')).toHaveCount(0);
  await page.getByLabel('Filter 1 value').fill(title);
  await page.getByRole('button', { name: 'apply ↵', exact: true }).click();
  await expect(page.locator('.sr-result').filter({ hasText: title })).toBeVisible();
  await page.keyboard.press('Control+k');
  const palette = page.getByRole('dialog', { name: 'Command palette' });
  await expect(palette).toBeVisible();
  await palette.getByPlaceholder('Search documents, tags, people — or type a command').fill(title);
  await expect(palette.getByText(title, { exact: true })).toBeVisible();
  await palette.getByText(title, { exact: true }).click();
  await expect(page).toHaveURL(new RegExp(`/documents/${doc.id}$`));
  await page.goto('/saved-views');
  await page.getByRole('button', { name: '+ New view', exact: true }).click();
  const viewName = uniqueName('Browser saved view');
  await page.getByLabel('name', { exact: true }).fill(viewName);
  await page.getByRole('switch', { name: 'Show on dashboard' }).click();
  await page.getByRole('switch', { name: 'Show in sidebar' }).click();
  await page.getByLabel('Rule type', { exact: true }).selectOption('title_contains');
  await page.getByLabel('Rule value', { exact: true }).fill(title);
  await page.getByRole('button', { name: '+ add', exact: true }).click();
  await page.getByRole('button', { name: 'Create', exact: true }).click();
  await page.getByRole('link', { name: viewName, exact: true }).click();
  await expect(page.getByText(title, { exact: true })).toBeVisible();
  await page.goto('/');
  await expect(page.locator('.db-views').getByRole('link', { name: viewName, exact: true })).toBeVisible();
  await page.getByRole('group', { name: 'Pinned saved views' }).getByRole('link', { name: viewName, exact: true }).click();
  await expect(page.getByRole('heading', { name: viewName, exact: true })).toBeVisible();
  await expect(page.getByText(title, { exact: true })).toBeVisible();
});

test('comments edit/delete, checkout/checkin and password public shares work from the browser', async ({ page, request, browser }) => {
  test.setTimeout(240_000);
  const token = await login(request);
  const { doc, bytes } = await uploadPdf(request, token);
  await authenticatePage(page, token);
  await page.goto(`/documents/${doc.id}`);
  await page.getByRole('button', { name: 'Check out', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Check in', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Check in', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Check out', exact: true })).toBeVisible();
  await page.getByRole('tab', { name: 'Notes', exact: true }).click();
  const note = uniqueName('Browser comment');
  await page.getByRole('textbox', { name: 'Add a note', exact: true }).fill(note);
  await page.getByRole('button', { name: 'Post note', exact: true }).click();
  await expect(page.getByText(note, { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Edit comment', exact: true }).click();
  await page.getByRole('textbox', { name: 'Edit comment', exact: true }).fill(`${note} edited`);
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  await expect(page.getByText(`${note} edited`, { exact: true })).toBeVisible();
  page.once('dialog', (dialog) => dialog.accept());
  await page.getByRole('button', { name: 'Delete comment', exact: true }).click();
  await expect(page.getByText(`${note} edited`, { exact: true })).toHaveCount(0);
  await page.getByRole('tab', { name: 'Details', exact: true }).click();
  await page.getByLabel('password (optional)', { exact: true }).fill('Browser-share-secret!');
  const shareResponse = page.waitForResponse((response) => response.url().endsWith(`/documents/${doc.id}/share/`) && response.request().method() === 'POST');
  await page.getByRole('button', { name: 'Create link', exact: true }).click();
  const share = await (await shareResponse).json();
  expect(share.slug).toBeTruthy();
  const publicContext = await browser.newContext();
  const publicPage = await publicContext.newPage();
  await publicPage.goto(`${baseURL}/share/${share.slug}`);
  await expect(publicPage.getByText('password required', { exact: true })).toBeVisible();
  await publicPage.getByLabel('password', { exact: true }).fill('wrong-password');
  await publicPage.getByRole('button', { name: 'Access document →' }).click();
  await expect(publicPage.getByText('Incorrect password.', { exact: true })).toBeVisible();
  await publicPage.getByLabel('password', { exact: true }).fill('Browser-share-secret!');
  await publicPage.getByRole('button', { name: 'Access document →' }).click();
  await expect(publicPage.getByRole('heading', { name: doc.title, exact: true })).toBeVisible();
  const downloadPromise = publicPage.waitForEvent('download');
  await publicPage.getByRole('link', { name: '↓ Download', exact: true }).click();
  const download = await downloadPromise;
  expect(sha256(await readFile((await download.path())!))).toBe(sha256(bytes));
  await publicContext.close();
  const links = await request.get(`${baseURL}/api/v1/share-links/`, { headers: authHeaders(token) });
  const response = await links.json();
  expect((response.results || response).find((item: { id: number }) => item.id === share.id).download_count).toBe(1);
});
